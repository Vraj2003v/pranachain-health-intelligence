"""PranaPulse prototype: upload patient workbooks, see explainable changes, evidence and a trend projection.

Run with:  streamlit run app.py
"""
import io

import pandas as pd
import plotly.graph_objects as go
import streamlit as st

from pranapulse import forecast, llm
from pranapulse.demo_data import all_demo_workbooks
from pranapulse.detect import detect
from pranapulse.loader import load_patient
from pranapulse.signals import SIGNALS, WINDOW_DAYS

st.set_page_config(page_title="PranaPulse", page_icon="🫀", layout="wide")

BADGE = {"Sufficient": '<span class="chip ok">● Data sufficient</span>',
         "Limited": '<span class="chip warn">● Limited data</span>'}
st.markdown("""
<style>
.block-container {padding-top: 4rem; max-width: 1200px;}
.hero {background: linear-gradient(120deg,#1f4e79 0%,#2d7a9a 100%); color:#fff; border-radius:16px; padding:22px 26px; margin-bottom:14px;}
.hero h1 {color:#fff; margin:0; font-size:2rem; padding:0;}
.hero p {margin:4px 0 0 0; opacity:.92; font-size:1rem;}
.hero .meta {margin-top:10px; font-size:.9rem; opacity:.85;}
.chip {display:inline-block; padding:2px 10px; border-radius:999px; font-size:.78rem; font-weight:600; margin-right:6px;}
.chip.ok {background:#e3f4ea; color:#1d6b3a;} .chip.warn {background:#fff1dc; color:#9a5b00;}
.chip.kind {background:#e8eef6; color:#1f4e79;}
.kpi {border:1px solid rgba(128,128,128,.25); border-radius:14px; padding:14px 18px;}
.kpi .n {font-size:2rem; font-weight:700; line-height:1.1;} .kpi .l {opacity:.7; font-size:.85rem;}
.step {border:1px solid rgba(128,128,128,.25); border-radius:14px; padding:16px 18px; height:100%;}
.step b {color:#1f4e79;}
.note {border-left:4px solid #c55a11; padding:6px 12px; background:rgba(197,90,17,.07); border-radius:0 8px 8px 0; font-size:.9rem;}
@media (max-width: 640px) {.hero h1 {font-size:1.5rem;} .kpi .n {font-size:1.5rem;}}
</style>
""", unsafe_allow_html=True)
ICON = {"pattern": "🔗", "single": "📈", "cycle": "🗓️"}
COLORS = {"line": "#1f4e79", "dots": "rgba(31,78,121,0.22)", "proj": "#c55a11", "band": "rgba(197,90,17,0.16)"}


@st.cache_data(show_spinner=False)
def parse(data: bytes):
    p = load_patient(io.BytesIO(data))
    return p, *detect(p)


@st.cache_data(show_spinner=False)
def demo_files():
    return all_demo_workbooks()


# ------------------------------------------------------------------ sidebar
st.sidebar.title("🫀 PranaPulse")
st.sidebar.caption("Beyond the Record · Group 11 · COMP8967")
uploads = st.sidebar.file_uploader("Upload patient workbooks (.xlsx)", type=["xlsx"], accept_multiple_files=True)
use_demo = st.sidebar.toggle("Use fabricated demo patients", value=not uploads,
                             help="Five invented patients generated by the app, in the same layout as the real workbooks.")
files = {}
if use_demo:
    files.update(demo_files())
for u in uploads or []:
    files[u.name] = u.getvalue()

if not files:
    st.markdown('<div class="hero"><h1>🫀 PranaPulse</h1><p>Explainable changes in a patient\'s health, connected to their history.</p></div>',
                unsafe_allow_html=True)
    c1, c2, c3 = st.columns(3)
    c1.markdown('<div class="step"><b>1 · Load</b><br>Upload patient workbooks (.xlsx) in the sidebar, or switch on the fabricated demo patients.</div>', unsafe_allow_html=True)
    c2.markdown('<div class="step"><b>2 · Compare</b><br>Each patient is compared with their own earlier self, never with a population average.</div>', unsafe_allow_html=True)
    c3.markdown('<div class="step"><b>3 · Explain</b><br>You see what changed, the evidence, the history it connects to, and a projection.</div>', unsafe_allow_html=True)
    st.stop()

parsed, failed = {}, {}
bar = st.progress(0.0, text="Reading workbooks…") if len(files) > 5 else None
for i, (name, data) in enumerate(files.items(), 1):
    try:
        parsed[name] = parse(data)
    except Exception as exc:  # a workbook that does not match the layout
        failed[name] = str(exc)
    if bar:
        bar.progress(i / len(files), text=f"Reading workbooks… {i} of {len(files)}")
if bar:
    bar.empty()
for name, why in failed.items():
    st.sidebar.error(f"Could not read {name}: {why}")
if not parsed:
    st.stop()

flagged_only = st.sidebar.checkbox("Show only patients with an insight", value=False) if len(parsed) > 5 else False
names = [n for n, v in parsed.items() if v[1]] if flagged_only else list(parsed)
if not names:
    st.sidebar.info("No patient has an insight.")
    names = list(parsed)
choice = st.sidebar.selectbox("Patient", names, format_func=lambda n: f"{parsed[n][0].patient_id}  ·  {'Flagged' if parsed[n][1] else 'Quiet'}")
patient, insights, held, results = parsed[choice]

st.sidebar.divider()
use_llm = st.sidebar.toggle("Explain with local model", value=False,
                            help="Rewrites the summary with a local Ollama model (llama3.1:8b). Nothing leaves this computer. "
                                 "Falls back to the standard text if the model is off or its reply fails the wording check.")
if use_llm and not llm.available():
    st.sidebar.warning("Local model not found. Run: ollama pull llama3.1:8b (and keep Ollama running).")
    use_llm = False
st.sidebar.caption("Prototype for academic use on synthetic/anonymised data. It highlights patterns that may be worth "
                   "discussing with a healthcare provider. It does not diagnose or give medical advice.")

# ------------------------------------------------------------------ header
start, end = patient.window
st.markdown(f'<div class="hero"><h1>🫀 Patient {patient.patient_id}</h1>'
            f'<p>Changes against this patient\'s own baseline, connected to their history.</p>'
            f'<div class="meta">{patient.profile.get("Age", "—")} years · {patient.profile.get("Sex", "—")} · '
            f'data {start:%d %b %Y} – {end:%d %b %Y} ({len(patient.daily)} days)</div></div>', unsafe_allow_html=True)

tab_over, tab_ins, tab_time, tab_cov = st.tabs(["Overview", "Insights", "Timeline & projection", "Data coverage"])

# ------------------------------------------------------------------ overview
with tab_over:
    rows = []
    for name, (p, ins, hd, res) in parsed.items():
        top = ins[0] if ins else None
        rows.append({"Patient": p.patient_id, "Age": p.profile.get("Age"), "Sex": p.profile.get("Sex"),
                     "Status": "Flagged" if top else "Quiet",
                     "What was found": top.title if top else "Nothing beyond usual variation",
                     "Data flag": ("Limited data" if top and top.flag == "Limited" else ("Sufficient" if top else "—")),
                     "Held back": len(hd)})
    df = pd.DataFrame(rows)
    n_flag = int((df.Status == "Flagged").sum())
    n_lim = int((df["Data flag"] == "Limited data").sum())
    k = st.columns(4)
    for col, num, lab in zip(k, [len(df), n_flag, len(df) - n_flag, n_lim],
                             ["Patients loaded", "With an insight", "Quiet (intended)", "Limited-data insights"]):
        col.markdown(f'<div class="kpi"><div class="n">{num}</div><div class="l">{lab}</div></div>', unsafe_allow_html=True)
    st.write("")
    f1, f2, f3 = st.columns([2, 2, 3])
    show = f1.selectbox("Show", ["All patients", "With an insight", "Quiet"])
    kinds = f2.selectbox("Data flag", ["Any", "Sufficient", "Limited data"])
    q = f3.text_input("Search patient ID", placeholder="e.g. PC0103")
    view = df
    if show == "With an insight":
        view = view[view.Status == "Flagged"]
    elif show == "Quiet":
        view = view[view.Status == "Quiet"]
    if kinds != "Any":
        view = view[view["Data flag"] == kinds]
    if q:
        view = view[view.Patient.astype(str).str.contains(q, case=False)]
    view = view.assign(Status=view.Status.map({"Flagged": "🟠 Flagged", "Quiet": "⚪ Quiet"}))
    st.dataframe(view, hide_index=True, width="stretch", height=min(560, 60 + 35 * len(view)),
                 column_config={"Patient": st.column_config.TextColumn(width="small"),
                                "What was found": st.column_config.TextColumn(width="large"),
                                "Held back": st.column_config.NumberColumn(help="Changes noticed but not shown because the data was too thin")})
    left, right = st.columns([4, 1])
    left.caption(f"Showing {len(view)} of {len(df)}. Pick a patient in the sidebar to see the insight, evidence and projection. "
                 "Quiet is intended: ordinary day-to-day variation is not reported.")
    right.download_button("Download table (CSV)", df.to_csv(index=False).encode(), "pranapulse_overview.csv", "text/csv")

# ------------------------------------------------------------------ insights
with tab_ins:
    if not insights:
        st.success("Nothing flagged. No meaningful change was found against this patient's own baseline.")
        st.caption("Staying quiet is intended: small day-to-day variation is not reported as an insight.")
    for ins in insights:
        with st.container(border=True):
            st.markdown(f"### {ICON[ins.kind]} {ins.title}")
            kind_label = {"pattern": "Pattern across measures", "single": "Single measure", "cycle": "Cycle timing"}[ins.kind]
            st.markdown(f'<span class="chip kind">{kind_label}</span>' + BADGE[ins.flag]
                        + ('<span style="opacity:.7;font-size:.85rem"> some expected data was missing</span>' if ins.flag == "Limited" else ""),
                        unsafe_allow_html=True)
            if use_llm:
                text, source = llm.explain(ins)
                st.markdown(f"**{text}**")
                st.caption(f"Wording by: {source}")
            else:
                st.markdown(f"**{ins.summary}**" if ins.summary else "")
            tiles = [results[k] for k in ins.signals if k in results]
            if tiles:
                cols = st.columns(min(len(tiles), 4))
                for col, r in zip(cols, tiles):
                    col.metric(r.label, f"{r.mean_last:,.{r.decimals}f} {r.unit}",
                               f"{r.diff:+,.{r.decimals}f} vs earlier 90 days", delta_color="off")
            for line in ins.bullets:
                st.markdown(f"- {line}")
            if ins.context:
                st.caption("Connects to: " + " · ".join(x.split(" — ")[0] for x in ins.context[:3]))
            if ins.closing:
                st.markdown(f'<div class="note">{ins.closing}</div>', unsafe_allow_html=True)
            with st.expander("Why was this flagged? Supporting evidence"):
                st.dataframe(pd.DataFrame(ins.evidence).rename(columns={
                    "signal": "Signal", "source": "Source sheet", "first_window": "Earlier period", "last_window": "Recent period",
                    "first_mean": "Earlier value", "last_mean": "Recent value", "days_with_data": "Days with data",
                    "overall_coverage": "Overall coverage", "size_vs_own_variation": "Change vs usual variation",
                    "trend_p": "Trend p-value"}), hide_index=True, width="stretch")
            if ins.context:
                with st.expander("History this connects to (with source)"):
                    for line in ins.context:
                        st.markdown(f"- {line}")
            if ins.asks:
                with st.expander("What additional data would improve understanding"):
                    for line in ins.asks:
                        st.markdown(f"- {line}")
    if held:
        with st.expander("Held back (not shown as insights)"):
            for line in held:
                st.markdown(f"- {line}")
    better = [r for r in results.values() if r.direction == "improving" and r.flag != "Insufficient"]
    if better:
        with st.expander("Positive changes"):
            for r in better:
                st.markdown(f"- {r.label} moved from {r.mean_first:,.{r.decimals}f} to {r.mean_last:,.{r.decimals}f} {r.unit}")

# ------------------------------------------------------------------ timeline
with tab_time:
    keys = list(SIGNALS)
    default = keys.index(insights[0].forecast_key) if insights and insights[0].forecast_key in SIGNALS else 0
    key = st.selectbox("Signal", keys, format_func=lambda k: f"{SIGNALS[k].label} ({SIGNALS[k].unit})", index=default)
    sig = SIGNALS[key]
    s = patient.daily[sig.column]
    fig = go.Figure()
    fig.add_trace(go.Scatter(x=s.index, y=s, mode="markers", name="Daily value", marker=dict(size=4, color=COLORS["dots"])))
    wk = forecast.weekly_means(s)
    fig.add_trace(go.Scatter(x=wk.index, y=wk, mode="lines", name="Weekly average", line=dict(color=COLORS["line"], width=3)))
    r = results.get(key)
    if r is not None:
        for (x0, x1), label, mean in [(r.window_first, "Earlier", r.mean_first), (r.window_last, "Recent", r.mean_last)]:
            fig.add_vrect(x0=x0, x1=x1, fillcolor="rgba(120,120,120,0.08)", line_width=0,
                          annotation_text=f"{label} 90 days · avg {mean:,.{sig.decimals}f} {sig.unit}" if mean == mean else label,
                          annotation_position="top left")
    proj = forecast.project(s)
    if proj is not None:
        fig.add_trace(go.Scatter(x=list(proj.date) + list(proj.date[::-1]), y=list(proj.high) + list(proj.low[::-1]),
                                 mode="lines", fill="toself", fillcolor=COLORS["band"], line=dict(width=0),
                                 name="95% range", hoverinfo="skip"))
        fig.add_trace(go.Scatter(x=proj.date, y=proj["mean"], mode="lines", name="Projection",
                                 line=dict(color=COLORS["proj"], width=3, dash="dash")))
    marks = [(row.date, row.event) for row in patient.history.itertuples()]
    marks += [(row.start, f"{row.medication} started") for row in patient.meds.itertuples() if row.start == row.start]
    for when, text in marks:
        if when >= start:
            fig.add_shape(type="line", x0=when, x1=when, y0=0, y1=1, yref="paper", line=dict(color="#7f7f7f", width=1, dash="dot"))
            fig.add_annotation(x=when, y=1, yref="paper", text=text, showarrow=False, textangle=-90, xanchor="left",
                               yanchor="top", font=dict(size=10, color="#555"))
    before = [f"{text} ({when:%b %Y})" for when, text in marks if when < start]
    if before:
        fig.add_annotation(x=0, y=-0.2, xref="paper", yref="paper", showarrow=False, xanchor="left", align="left",
                           text="◀ Before this window: " + "; ".join(before), font=dict(size=11, color="#555"))
    fig.update_layout(height=480, margin=dict(l=10, r=10, t=30, b=60), yaxis_title=f"{sig.label} ({sig.unit})",
                      legend=dict(orientation="h", y=1.08), hovermode="x unified")
    st.plotly_chart(fig, width="stretch")
    if proj is None:
        st.caption("Not enough weekly data to draw a projection for this signal.")
    else:
        st.caption(f"The dashed line is a straight-line projection of the last 26 weeks, {len(proj)} weeks ahead, with a 95% range. "
                   "It shows what happens if the recent trend simply continues; it is not a prediction of health outcomes.")

    tests = sorted(patient.labs.test.unique())
    if tests:
        t = st.selectbox("Lab result", tests, index=tests.index("HbA1c") if "HbA1c" in tests else 0)
        rows = patient.labs[patient.labs.test == t]
        lf = go.Figure(go.Scatter(x=rows.date, y=rows.result, mode="lines+markers+text", text=[f"{v:g}" for v in rows.result],
                                  textposition="top center", line=dict(color=COLORS["line"]), name=t))
        lo, hi = rows.ref_low.iloc[0], rows.ref_high.iloc[0]
        if lo == lo and hi == hi:
            lf.add_hrect(y0=lo, y1=hi, fillcolor="rgba(46,160,67,0.12)", line_width=0, annotation_text="Reference range",
                         annotation_position="top left")
        lf.update_layout(height=300, margin=dict(l=10, r=10, t=30, b=10), yaxis_title=f"{t} ({rows.unit.iloc[0]})")
        st.plotly_chart(lf, width="stretch")

# ------------------------------------------------------------------ coverage
with tab_cov:
    rows = []
    for r in results.values():
        rows.append({"Signal": r.label, "Source sheet": r.sheet, "Days with data": f"{r.coverage:.0%}",
                     f"Earlier {WINDOW_DAYS} days": r.n_first, f"Recent {WINDOW_DAYS} days": r.n_last,
                     "Change": "—" if r.diff != r.diff else f"{r.diff:+,.{r.decimals}f} {r.unit}",
                     "Result": r.direction.capitalize(), "Data flag": r.flag})
    st.dataframe(pd.DataFrame(rows), hide_index=True, width="stretch")
    st.caption("Data flag: Sufficient = at least 85% of days and 72 of the first and last 90 days; Limited = at least 60% and 45 days, "
               "shown with a badge; Insufficient = not reported as an insight. The flag describes how much data was available, "
               "not how certain the model is. Thresholds are placeholders pending calibration on real patients.")
